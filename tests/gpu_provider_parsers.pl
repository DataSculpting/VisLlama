use strict;
use warnings;
use Test::More;
use FindBin qw($RealBin);
use lib "$RealBin/../lib";
use JSON::PP qw(decode_json encode_json);
use Digest::SHA qw(sha256_hex);
use VisLlama::GPUParsers ();
sub read_file {open my $fh,'<:raw',$_[0] or die $!;local $/;return <$fh>}
sub fixture {read_file("$RealBin/fixtures/gpu-providers/$_[0]")}
sub rejected {my ($fn,$why)=@_;eval {$fn->()};ok($@,$why)}
my $amd=VisLlama::GPUParsers::amd_inventory(fixture('amd-list.json'));
my $static=VisLlama::GPUParsers::amd_rows(fixture('amd-static.json'));
my $sample=VisLlama::GPUParsers::amd_sample($amd,$static,fixture('amd-metric.json'));
is($sample->[0]{memory_used_mib},2048,'AMD binary MB output is preserved as MiB, not converted as decimal MB');
is($sample->[0]{memory_total_mib},16384,'AMD capacity is the matching VRAM pool');
is($sample->[0]{fan_percent},0,'Stopped fan is a valid zero');
is($sample->[0]{utilization_percent},0,'Idle is a valid zero');
is($sample->[0]{power_limit_w},250,'Active PPT0 socket cap is used');
is($sample->[0]{semantics}{temperature_sensor},'edge','Temperature source is explicit');
ok(!$sample->[0]{explicit_placement_ready},'Monitoring never enables physical placement');
is($sample->[0]{pci_bus_id},'00000000:0b:00.0','PCI domains are normalized');
my $raw=decode_json(fixture('amd-metric.json'));
$raw->[0]{temperature}{edge}='N/A';$raw->[0]{fan}{usage}='N/A';
$sample=VisLlama::GPUParsers::amd_sample($amd,[],encode_json($raw));
is($sample->[0]{temperature_c},60,'Hotspot fallback is supported');
is($sample->[0]{semantics}{temperature_sensor},'hotspot','Fallback is labeled rather than disguised as edge');
is($sample->[0]{fan_percent},undef,'RPM is never substituted as fan percentage');
is($sample->[0]{power_limit_w},undef,'Unknown cap stays null');
$raw->[0]{mem_usage}{used_vram}{unit}='GB';
$sample=VisLlama::GPUParsers::amd_sample($amd,[],encode_json($raw));
is($sample->[0]{memory_used_mib},undef,'Unvalidated unit is not guessed');
rejected(sub {VisLlama::GPUParsers::amd_inventory('[{"gpu":0},{"gpu":0}]')},'Duplicate CLI ordinals rejected');
rejected(sub {VisLlama::GPUParsers::amd_sample($amd,[],'[{"gpu":1,"usage":{}}]')},'Changed enumeration rejected');
rejected(sub {VisLlama::GPUParsers::amd_sample($amd,[],'[{"gpu":0,"surprise":42}]')},'Unknown metric schema rejected');
my $rocm=VisLlama::GPUParsers::rocm_inventory(fixture('rocm-list.json'));
$sample=VisLlama::GPUParsers::rocm_sample($rocm,fixture('rocm-metric.json'));
is($sample->[0]{memory_used_mib},2048,'ROCm bytes convert to MiB');
is($sample->[0]{uuid},undef,'Legacy unique ID is not invented into a UUID');
is($sample->[0]{provider_unique_id},'0x1234','Legacy unique ID retained in its own namespace');
is($sample->[0]{power_limit_w},undef,'Maximum package power is not an active cap');
is(scalar(@$sample),2,'Identical marketing names are distinct records');
my $intel=VisLlama::GPUParsers::intel_inventory(fixture('intel-discovery.json'));
is(scalar(@$intel),1,'Documented Discrete GPU device type accepted');
$sample=VisLlama::GPUParsers::intel_sample($intel,\@VisLlama::GPUParsers::INTEL_FIELDS,fixture('intel-metric.csv'));
is($sample->[0]{name},'Synthetic, Intel','Quoted comma in Intel GPU name parsed');
is($sample->[0]{fan_percent},undef,'Intel N/A becomes null');
is($sample->[0]{power_w},72,'Card watts parsed');
is($sample->[0]{semantics}{utilization},'busiest engine','Utilization semantics retained');
rejected(sub {VisLlama::GPUParsers::intel_sample($intel,\@VisLlama::GPUParsers::INTEL_FIELDS,'0, bad')},'Wrong CSV column count rejected');
rejected(sub {VisLlama::GPUParsers::csv('0,"unterminated')},'Malformed quoted CSV rejected');
rejected(sub {VisLlama::GPUParsers::json('banner {"device_list":[]}')},'Unrecognized banner is not stripped heuristically');
rejected(sub {VisLlama::GPUParsers::json('{"error":"denied"}')},'Exit-zero JSON errors rejected');
is_deeply(VisLlama::GPUParsers::intel_inventory('{"device_list":null}'),[],'Documented no-device null is an empty inventory');
for my $v ('N/A','error 12','NaN','Infinity',JSON::PP::true,{value=>12},'12 W') {is(VisLlama::GPUParsers::number($v),undef,'Invalid measurement stays unknown')}
is(VisLlama::GPUParsers::uuid('00000000-0000-0000-0000-000000000000'),undef,'Placeholder UUID is not identity evidence');
is(VisLlama::GPUParsers::bdf('0000:01:ff.0'),undef,'Invalid PCI device number rejected');
my $detail=VisLlama::GPUParsers::intel_detail($intel->[0],fixture('intel-detail.json'));
my $json_sample=VisLlama::GPUParsers::intel_stats_sample($detail,fixture('intel-stats.json'));
is($json_sample->{memory_used_mib},2048,'Verified single-tile JSON memory is normalized');
is($json_sample->{utilization_percent},0,'Single-tile JSON idle value retained');
is($json_sample->{power_w},undef,'JSON power without validated domain is omitted');
$detail->{_tiles}=2;
$json_sample=VisLlama::GPUParsers::intel_stats_sample($detail,fixture('intel-stats.json'));
is($json_sample->{memory_used_mib},undef,'One tile is never presented as a multi-tile GPU total');
ok(!exists($json_sample->{_tiles}),'Internal parser fields do not leak into public records');
rejected(sub {VisLlama::GPUParsers::intel_stats_sample($detail,'{"device_id":0,"device_level":[]}')},'Unvalidated legacy stats schema rejected');
my $baseline=decode_json(fixture('nvidia-baseline.json'));
my $source=read_file("$RealBin/../lib/VisLlama/Telemetry.pm");$source =~ /(sub collect_nvidia_gpu_stats.*?)(?=\n# -----------------------------------------------------------------------------)/s or die 'Missing collector';
is(sha256_hex($1),$baseline->{nvidia_collector_sha256},'Existing NVIDIA collector is byte-for-byte unchanged');
is(sha256_hex(read_file("$RealBin/../lib/VisLlama/GPUIsolation.pm")),$baseline->{gpu_isolation_sha256},'Existing CUDA identity and local remapping remain byte-for-byte unchanged');
is(sha256_hex(read_file("$RealBin/../lib/VisLlama/GPUPlanner.pm")),$baseline->{gpu_planner_sha256},'Existing planner behavior and CUDA gates remain byte-for-byte unchanged');
done_testing();
