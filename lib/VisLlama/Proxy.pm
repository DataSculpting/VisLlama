package VisLlama::Proxy;

# Public OpenAI-compatible HTTP forwarding with per-request routing. Model
# load handoff goes to the control process so calculated placement stays serialized.
use strict;
use warnings;
use IO::Socket::INET;
use JSON::PP qw(encode_json decode_json);
use threads;
use HTTP::Tiny;
use VisLlama::Errors ();
use VisLlama::Storage ();
use VisLlama::ProxyResponse ();
use VisLlama::StreamReader ();
our $CHAT_CORS = '';
our $RESPONSE_STARTED = '';

my %opt = (
    listen_host => '127.0.0.1',
    listen_port => 8080,
    route_map => '',
);

# -----------------------------------------------------------------------------
# Load the alias-to-backend routing table generated by the main VisLlama process.
# -----------------------------------------------------------------------------
sub load_route_map {
    my $txt=VisLlama::Storage::read($opt{route_map});
    die 'Route map is unavailable' unless defined $txt;
    my $j = decode_json($txt);
    die "Invalid route map\n" unless ref($j) eq 'HASH' && ref($j->{backends}) eq 'ARRAY';
    return $j;
}

# -----------------------------------------------------------------------------
# Write an entire response/request buffer to a socket.
# -----------------------------------------------------------------------------
sub write_all { return VisLlama::ProxyResponse::write_all(@_); }

# -----------------------------------------------------------------------------
# Return a small JSON response from the proxy.
# -----------------------------------------------------------------------------
sub send_json {
    my ($sock, $code, $reason, $obj) = @_;
    # All locally generated proxy errors share the same fail-closed boundary.
    if (ref($obj) eq 'HASH' && exists($obj->{error})) {
        my $error=$obj->{error};
        return VisLlama::ProxyResponse::send_error($sock,$code,
            ref($error) eq 'HASH' ? $error->{message} : $error,
            ref($error) eq 'HASH' ? $error->{type} : 'proxy_error',
            sub { $RESPONSE_STARTED=$_[0] },$CHAT_CORS);
    }
    $RESPONSE_STARTED='json';
    my $body = encode_json($obj);
    my $head = "HTTP/1.1 $code $reason\r\n${CHAT_CORS}Content-Type: application/json; charset=utf-8\r\nContent-Length: " . length($body) . "\r\nCache-Control: no-store\r\nConnection: close\r\n\r\n";
    write_all($sock, $head . $body);
}

# -----------------------------------------------------------------------------
# Read and parse HTTP request/response headers.
# -----------------------------------------------------------------------------
sub read_headers {
    my ($sock) = @_;
    my $request = <$sock>; return unless defined $request;
    $request =~ s/\r?\n$//;
    my ($method, $path, $version) = split /\s+/, $request, 3;
    die 'Invalid HTTP request' unless defined($method) && defined($path);
    my @raw; my %h; my $complete=0;
    while (my $line = <$sock>) {
        if ($line =~ /^\r?\n$/) {$complete=1;last;}
        push @raw, $line;
        my $x=$line; $x =~ s/\r?\n$//;
        my ($k,$v)=split /:\s*/, $x, 2;
        $v =~ s/[ \t]+\z// if defined $v;
        die 'Invalid HTTP headers' unless defined($v) && $k =~ /^[A-Za-z0-9!#$%&'*+.^_`|~-]+$/;
        die 'Ambiguous HTTP framing' if (lc($k) eq 'content-length' || lc($k) eq 'transfer-encoding') && exists $h{lc($k)};
        $h{lc($k)}=$v;
    }
    die 'Incomplete HTTP headers' unless $complete;
    return ($method,$path,$version||'HTTP/1.1',\@raw,\%h);
}

# -----------------------------------------------------------------------------
# Read a Content-Length framed HTTP body.
# -----------------------------------------------------------------------------
sub read_exact_body {
    my ($sock, $n) = @_;
    my $body='';
    while (length($body) < $n) {
        my $r=read($sock,my $part,$n-length($body));
        return undef unless $r;
        $body.=$part;
    }
    return $body;
}

# -----------------------------------------------------------------------------
# Read and dechunk an HTTP chunked-transfer body.
# -----------------------------------------------------------------------------
sub read_chunked_body {
    my ($sock) = @_;
    my $body='';
    while (1) {
        my $line=<$sock>; return undef unless defined $line;
        $line =~ s/\r?\n$//;
        my ($hex)=$line =~ /^([0-9A-Fa-f]{1,12})(?:;[^\r\n]*)?$/; return undef unless defined $hex;
        my $n=hex($hex);
        if ($n==0) {
            while (my $t=<$sock>) { return $body if $t =~ /^\r?\n$/; }
            return undef;
        }
        my $part=read_exact_body($sock,$n); return undef unless defined $part;
        $body.=$part;
        my $crlf=read_exact_body($sock,2);
        return undef unless defined($crlf) && $crlf eq "\r\n";
    }
}

# -----------------------------------------------------------------------------
# Select the correct request-body reader from the received headers.
# -----------------------------------------------------------------------------
sub read_request_body {
    my ($sock,$headers)=@_;
    if (exists $headers->{'transfer-encoding'}) {
        return undef unless $headers->{'transfer-encoding'} =~ /\Achunked\z/i && !exists $headers->{'content-length'};
        return read_chunked_body($sock);
    }
    my $length=$headers->{'content-length'} // '0';
    return undef unless $length =~ /\A[0-9]{1,12}\z/;
    my $n=0+$length;
    return '' unless $n>0;
    return read_exact_body($sock,$n);
}

# -----------------------------------------------------------------------------
# Send a request to one internal llama.cpp backend and collect a non-streaming response.
# -----------------------------------------------------------------------------
sub backend_request_collect {
    my ($host,$port,$method,$path,$body,$content_type)=@_;
    my $b=IO::Socket::INET->new(PeerAddr=>$host,PeerPort=>$port,Proto=>'tcp',Timeout=>8)
        or die "Cannot connect to internal router $host:$port: $!";
    $b->autoflush(1);
    my $req="$method $path HTTP/1.1\r\nHost: $host:$port\r\nConnection: close\r\n";
    if (defined $body && length $body) {
        $req .= "Content-Type: " . ($content_type||'application/json') . "\r\nContent-Length: " . length($body) . "\r\n";
    }
    $req .= "\r\n" . (defined($body)?$body:'');
    write_all($b,$req) or die "Failed writing backend request";
    my $status=<$b> // die "No backend response"; $status =~ s/\r?\n$//;
    my ($proto,$code,$reason)=split /\s+/,$status,3;
    my %h;
    while (my $line=<$b>) {
        last if $line =~ /^\r?\n$/;
        $line =~ s/\r?\n$//;
        my ($k,$v)=split /:\s*/,$line,2; $h{lc($k)}=$v if defined $v;
    }
    my $resp='';
    if (($h{'transfer-encoding'}//'') =~ /chunked/i) {
        while (1) {
            my $line=<$b>; last unless defined $line; $line =~ s/\r?\n$//;
            my ($hex)=$line =~ /^([0-9A-Fa-f]+)/; last unless defined $hex;
            my $n=hex($hex); last if $n==0;
            my $part=read_exact_body($b,$n); last unless defined $part; $resp.=$part; read($b,my $crlf,2);
        }
    } elsif (defined $h{'content-length'}) {
        $resp=read_exact_body($b,int($h{'content-length'})) // '';
    } else {
        while (1) { my $r=read($b,my $part,65536); last unless $r; $resp.=$part; }
    }
    close $b;
    return (int($code||500),$reason||'Backend Error',$resp);
}

# -----------------------------------------------------------------------------
# Return the public /v1/models response without leaking internal router metadata.
# -----------------------------------------------------------------------------
sub sanitize_models {
    my ($client)=@_;
    my $map=eval { load_route_map() };
    return send_json($client,500,'Internal Server Error',{error=>{message=>"$@",type=>'proxy_error'}}) if $@;
    my %seen; my @data;my %managed_ports;
    for my $alias (sort keys %{$map->{models}||{}}) {
        my $route=$map->{models}{$alias};next unless $route->{managed};
        push @data,{id=>$alias,object=>'model',owned_by=>$route->{engine}||'engine'};$seen{$alias}=1;
        $managed_ports{$route->{port}}=1;
    }
    for my $be (@{$map->{backends}}) {
        next unless ref($be) eq 'HASH';
        next if $managed_ports{$be->{port}};
        my ($code,$reason,$body)=eval { backend_request_collect($be->{host}||'127.0.0.1',int($be->{port}), 'GET','/v1/models',undef,undef) };
        if ($@ || $code<200 || $code>=300) {VisLlama::Errors::report($@ || $body,'backend_error');next;}
        my $src=eval { decode_json($body) }; next if $@ || ref($src) ne 'HASH' || ref($src->{data}) ne 'ARRAY';
        for my $m (@{$src->{data}}) {
            next unless ref($m) eq 'HASH' && defined $m->{id};
            next unless ref($map->{models}) eq 'HASH' && exists($map->{models}{$m->{id}});
            next if $seen{$m->{id}}++;
            my %clean=(id=>"$m->{id}",object=>'model',owned_by=>($map->{models}{$m->{id}}{engine}||'llamacpp'));
            $clean{created}=0+$m->{created} if defined($m->{created}) && $m->{created}=~/^\d+$/;
            push @data,\%clean;
        }
    }
    send_json($client,200,'OK',{object=>'list',data=>\@data});
}

# -----------------------------------------------------------------------------
# Resolve the requested OpenAI model ID to its assigned internal engine.
# -----------------------------------------------------------------------------
sub choose_backend {
    my ($body)=@_;
    my $map=load_route_map();
    my $model='';
    if (defined $body && length $body) {
        my $j=eval { decode_json($body) };
        $model=$j->{model}//'' if !$@ && ref($j) eq 'HASH';
    }
    if ($model) {
        if (ref($map->{models}) eq 'HASH' && ref($map->{models}{$model}) eq 'HASH') {
            return ($map->{models}{$model},$model,$map->{control});
        }
        return (undef,$model);
    }
    my $first=$map->{backends}[0];
    return ($first,$model,$map->{control}) if $first;
    die "No internal router backend is available";
}

# -----------------------------------------------------------------------------
# Forward a request to the selected engine; ProxyResponse owns safe replies.
# -----------------------------------------------------------------------------
sub proxy_http {
    my ($client,$method,$path,$version,$raw_headers,$headers,$body)=@_;
    my ($be,$model,$control)=eval { choose_backend($body) };
    if ($@) { return send_json($client,502,'Bad Gateway',{error=>{message=>"$@",type=>'proxy_error'}}); }
    if ($model && ref($be) ne 'HASH') { return send_json($client,404,'Not Found',{error=>{message=>'Unknown model',type=>'invalid_request_error'}}); }
    # Only calculated layer splits need controller-managed loading. The main
    # control loop serializes planning and waits for each child to become
    # resident before accepting another calculated model request.
    if ($model && ($be->{calculated} || $be->{managed})) {
        return send_json($client,502,'Bad Gateway',{error=>{message=>'Calculated model loader is unavailable',type=>'proxy_error'}})
            unless ref($control) eq 'HASH' && $control->{token};
        my $url = 'http://127.0.0.1:' . int($control->{port}) . '/api/router-ensure-load';
        my $response = HTTP::Tiny->new(timeout=>330, no_proxy=>['127.0.0.1', 'localhost'])->post($url,{
            headers=>{'content-type'=>'application/json'},
            content=>encode_json({model=>$model,token=>$control->{token}}),
        });
        my $result=eval {decode_json($response->{content}||'')};
        unless ($response->{success} && ref($result) eq 'HASH' && $result->{ok}) {
            my $detail = ref($result) eq 'HASH' ? ($result->{error} || 'Calculated model could not be loaded') : 'Invalid calculated load confirmation';
            return send_json($client,503,'Service Unavailable',{error=>{message=>$detail,type=>'model_load_error'}});
        }
    }
    my $host=$be->{host}||'127.0.0.1'; my $port=int($be->{port});
    my $backend=IO::Socket::INET->new(PeerAddr=>$host,PeerPort=>$port,Proto=>'tcp',Timeout=>10);
    return send_json($client,502,'Bad Gateway',{error=>{message=>'Internal llama.cpp router is unavailable',type=>'proxy_error'}}) unless $backend;
    $backend->autoflush(1);
    my $req="$method $path $version\r\n";
    for my $line (@$raw_headers) {
        next if $line =~ /^(?:Host|Connection|Proxy-Connection|Keep-Alive|Content-Length|Transfer-Encoding|Accept-Encoding)\s*:/i;
        $req.=$line;
    }
    $req.="Host: $host:$port\r\nConnection: close\r\nAccept-Encoding: identity\r\n";
    $req.="Content-Length: ".length($body)."\r\n" if defined($body) && length($body);
    $req.="\r\n".(defined($body)?$body:'');
    unless (write_all($backend,$req)) { close $backend; return; }

    my $reader=VisLlama::StreamReader->new($backend,$client);
    my $status=$reader->line();
    if (!defined $status) { close $backend; return send_json($client,502,'Bad Gateway',{error=>{message=>'Internal llama.cpp router returned no response',type=>'proxy_error'}}); }
    my $status_line=$status; $status_line =~ s/\r?\n$//;
    my ($proto,$code,$reason)=split /\s+/,$status_line,3; $code=int($code||500);
    my @rh; my %h;
    while (my $line=$reader->line()) {
        last if $line =~ /^\r?\n$/; push @rh,$line;
        my $x=$line; $x =~ s/\r?\n$//; my ($k,$v)=split /:\s*/,$x,2; $h{lc($k)}=$v if defined $v;
    }
    $h{'access-control-allow-origin'}=$headers->{origin} if length($CHAT_CORS) && !exists($h{'access-control-allow-origin'});
    VisLlama::ProxyResponse::relay($backend,$client,$method,$status_line,\%h,
        sub { $RESPONSE_STARTED=$_[0] },$headers->{origin},$reader);
    close $backend;
}

# -----------------------------------------------------------------------------
# Top-level handler for one accepted public client connection.
# -----------------------------------------------------------------------------
sub handle_client {
    my ($client)=@_; $client->autoflush(1);
    local $RESPONSE_STARTED='';
    local $CHAT_CORS='';
    eval {
        my @request=eval {read_headers($client)};
        return send_json($client,400,'Bad Request',{error=>{message=>$@,type=>'invalid_request_error'}}) if $@;
        my ($method,$path,$version,$raw_headers,$headers)=@request; return unless $method;
        # Chat uses the public API from the administration origin. Reflect only
        # a syntactically valid HTTP(S) origin on this one inference route.
        if ($path eq '/v1/chat/completions' && ($headers->{origin}//'') =~ m{\Ahttps?://(?:[A-Za-z0-9.-]+|\[[0-9A-Fa-f:]+\])(?::[0-9]{1,5})?\z}) {
            $CHAT_CORS='Access-Control-Allow-Origin: '.$headers->{origin}."\r\nVary: Origin\r\n";
            if ($method eq 'OPTIONS') {
                $RESPONSE_STARTED='body';write_all($client,"HTTP/1.1 204 No Content\r\n${CHAT_CORS}Access-Control-Allow-Methods: POST, OPTIONS\r\nAccess-Control-Allow-Headers: Authorization, Content-Type\r\nConnection: close\r\n\r\n");return;
            }
        }
        if ($path =~ m{^/models(?:/|$)}) { return send_json($client,404,'Not Found',{error=>{message=>'Not found',type=>'not_found'}}); }
        if ($method eq 'GET' && $path eq '/health') {load_route_map();return send_json($client,200,'OK',{status=>'ok'});}
        if ($method eq 'GET' && $path =~ m{^/v1/models(?:\?|$)}) { return sanitize_models($client); }
        my $body=read_request_body($client,$headers);
        return send_json($client,400,'Bad Request',{error=>{message=>'Incomplete or invalid request body',type=>'invalid_request_error'}}) unless defined $body;
        proxy_http($client,$method,$path,$version,$raw_headers,$headers,$body);
    };
    if ($@) {
        my $error=$@;
        if (!$RESPONSE_STARTED) {
            eval { send_json($client,500,'Internal Server Error',{error=>{message=>$error,type=>'proxy_error'}}) };
        } elsif ($RESPONSE_STARTED eq 'sse') {
            # Headers are already sent: emit an SSE error, never a second HTTP response.
            eval { write_all($client,"data: ".encode_json(VisLlama::ProxyResponse::envelope($error,'stream_error'))."\n\n") };
        } else { VisLlama::Errors::report($error,'proxy_error'); }
    }
    close $client;
}

# Load command-line routing configuration and accept public clients. Worker
# threads relay requests; the control process still owns calculated load planning.
sub run {
while (@ARGV) {
    my $k = shift @ARGV;
    my $v = shift @ARGV;
    die "Missing value for $k\n" unless defined $v;
    if    ($k eq '--listen-host') { $opt{listen_host} = $v; }
    elsif ($k eq '--listen-port') { $opt{listen_port} = int($v); }
    elsif ($k eq '--route-map')   { $opt{route_map} = $v; }
    else { die "Unknown option: $k\n"; }
}

die "--route-map is required\n" unless $opt{route_map};

my $server=IO::Socket::INET->new(LocalAddr=>$opt{listen_host},LocalPort=>$opt{listen_port},Proto=>'tcp',Listen=>64,ReuseAddr=>1)
    or die "Cannot listen on $opt{listen_host}:$opt{listen_port}: $!\n";
print "VisLlama OpenAI proxy listening on $opt{listen_host}:$opt{listen_port}; route map $opt{route_map}\n";
while (my $client=$server->accept()) { threads->create(\&handle_client,$client)->detach(); }

    return 0;
}

1;
